// Runs in the YouTube page's main world (chrome.scripting world "MAIN"),
// injected on demand when the user turns subtitles on. Kept small and
// read-only: it observes the caption responses the player downloads itself
// and never changes what the player receives.
//
// Why the main world: the player's XMLHttpRequest and its API methods
// (getPlayerResponse, getVideoData) only exist there; the content script's
// isolated world sees the same DOM but not page JavaScript.
//
// Why read the player's own requests instead of fetching captions: YouTube
// signs caption URLs and adds a proof-of-origin token (`pot`) generated by the
// player, so a self-built request is easily rejected (empty body or 429).

import {
  YT_COMMAND_EVENT,
  YT_HOOK_EVENT,
  isTimedtextUrl,
  parseHookCommand,
  type HookEvent,
  type PlayerInfo,
} from "../shared/youtube-bridge";

interface YtPlayer extends HTMLElement {
  getPlayerResponse?: () => YtPlayerResponse | null | undefined;
  getVideoData?: () => { video_id?: string } | null | undefined;
  toggleSubtitles?: () => void;
}

interface YtPlayerResponse {
  videoDetails?: { videoId?: string; isLive?: boolean };
  captions?: {
    playerCaptionsTracklistRenderer?: {
      captionTracks?: Array<{ languageCode?: string; kind?: string; baseUrl?: string }>;
    };
  };
}

declare global {
  interface Window {
    __llmtYtHook?: boolean;
  }
}

if (!window.__llmtYtHook) {
  window.__llmtYtHook = true;
  install();
}

function install(): void {
  /** Captions are forwarded only while subtitles are on. */
  let enabled = false;
  /** We turned CC on ourselves; turned back off with subtitles, so YouTube's captions do not linger. */
  let ccTurnedOn = false;

  // The main player; thumbnail hover previews use other player elements and
  // also download captions, which must be ignored.
  const player = () => document.getElementById("movie_player") as YtPlayer | null;

  const mainVideoId = (): string | null => {
    const p = player();
    try {
      return p?.getVideoData?.()?.video_id || p?.getPlayerResponse?.()?.videoDetails?.videoId || null;
    } catch {
      return null;
    }
  };

  const emit = (ev: HookEvent) =>
    document.dispatchEvent(new CustomEvent(YT_HOOK_EVENT, { detail: JSON.stringify(ev) }));

  const proto = XMLHttpRequest.prototype;
  const origOpen = proto.open;
  const origSend = proto.send;
  const urls = new WeakMap<XMLHttpRequest, string>();

  proto.open = function (this: XMLHttpRequest, ...args: unknown[]) {
    urls.set(this, String(args[1]));
    return (origOpen as (...a: unknown[]) => void).apply(this, args);
  } as typeof proto.open;

  proto.send = function (this: XMLHttpRequest, ...args: unknown[]) {
    const raw = urls.get(this);
    const url = enabled && raw ? isTimedtextUrl(raw, location.href) : null;
    if (url) this.addEventListener("load", () => onCaptionLoad(this, url), { once: true });
    return (origSend as (...a: unknown[]) => void).apply(this, args);
  } as typeof proto.send;

  function onCaptionLoad(xhr: XMLHttpRequest, url: URL): void {
    if (!enabled || xhr.status !== 200) return;
    if (xhr.responseType !== "" && xhr.responseType !== "text") return;
    const videoId = url.searchParams.get("v");
    if (!videoId || videoId !== mainVideoId()) return; // a hover preview, or a stale request
    emit({ type: "captions", videoId, url: url.href, body: xhr.responseText });
  }

  function info(): PlayerInfo {
    let resp: YtPlayerResponse | null | undefined;
    try {
      resp = player()?.getPlayerResponse?.();
    } catch {
      resp = null;
    }
    const tracks = resp?.captions?.playerCaptionsTracklistRenderer?.captionTracks ?? [];
    return {
      videoId: mainVideoId(),
      isLive: resp?.videoDetails?.isLive === true,
      tracks: tracks
        .filter((t) => typeof t.languageCode === "string" && typeof t.baseUrl === "string")
        .map((t) => ({ lang: t.languageCode!, kind: t.kind ?? null, baseUrl: t.baseUrl! })),
    };
  }

  /**
   * Makes the player download captions again. Clicking the CC button (rather
   * than calling toggleSubtitles()) is what YouTube remembers as the user's
   * preference, so the next video in the same tab requests captions by itself.
   */
  function requestCaptions(): void {
    const p = player();
    const btn = ccButton();
    if (btn) {
      if (btn.getAttribute("aria-pressed") === "true") {
        btn.click();
        setTimeout(() => btn.click(), 150);
      } else {
        btn.click();
        ccTurnedOn = true;
      }
      return;
    }
    try {
      p?.toggleSubtitles?.();
    } catch {
      /* player API changed: the content script reports the missing captions */
    }
  }

  function ccButton(): HTMLElement | null {
    return player()?.querySelector<HTMLElement>(".ytp-subtitles-button") ?? null;
  }

  async function fetchTrack(id: number, raw: string): Promise<void> {
    const url = isTimedtextUrl(raw, location.href);
    if (!url) {
      emit({ type: "fetched", id, status: 0, body: null });
      return;
    }
    try {
      const res = await fetch(url.href, { credentials: "same-origin" });
      emit({ type: "fetched", id, status: res.status, body: res.ok ? await res.text() : null });
    } catch {
      emit({ type: "fetched", id, status: 0, body: null });
    }
  }

  document.addEventListener(YT_COMMAND_EVENT, (e) => {
    const cmd = parseHookCommand((e as CustomEvent).detail);
    if (!cmd) return;
    switch (cmd.cmd) {
      case "enable":
        enabled = true;
        emit({ type: "info", id: cmd.id, info: info() });
        break;
      case "disable": {
        enabled = false;
        const btn = ccButton();
        if (ccTurnedOn && btn?.getAttribute("aria-pressed") === "true") btn.click();
        ccTurnedOn = false;
        break;
      }
      case "info":
        emit({ type: "info", id: cmd.id, info: info() });
        break;
      case "request-captions":
        requestCaptions();
        break;
      case "fetch":
        void fetchTrack(cmd.id, cmd.url);
        break;
    }
  });
}
